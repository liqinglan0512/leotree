type Key = keyof typeof ZH;
type Vars = Record<string, string | number>;

function fill(s: string, vars?: Vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function translate(locale: Locale, key: Key, vars?: Vars) {
  const table = locale === "en" ? EN : ZH;
  return fill(table[key] ?? ZH[key], vars);
}

interface I18nValue {
  locale: Locale;
  font: FontSize;
  prefs: Prefs;
  t: (key: Key, vars?: Vars) => string;
  setLocale: (locale: Locale) => void;
  setFont: (font: FontSize) => void;
}

const I18nCtx = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [prefs, setPrefs] = useState<Prefs>(() => {
    const p = loadPrefs();
    applyPrefs(p);
    return p;
  });
  const value = useMemo<I18nValue>(() => {
    const setLocale = (locale: Locale) => {
      const next = { ...prefs, locale };
      savePrefs(next);
      setPrefs(next);
    };
    const setFont = (font: FontSize) => {
      const next = { ...prefs, font };
      savePrefs(next);
      setPrefs(next);
    };
    return {
      locale: prefs.locale,
      font: prefs.font,
      prefs,
      t: (key, vars) => translate(prefs.locale, key, vars),
      setLocale,
      setFont,
    };
  }, [prefs]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n");
  return ctx;
}
